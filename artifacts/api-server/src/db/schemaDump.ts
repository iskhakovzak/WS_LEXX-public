/**
 * Deterministic schema dump of the `public` schema from the catalogs (no pg_dump needed, so it works the same on
 * Windows dev machines, CI and Replit regardless of client versions). The output is executable SQL:
 *
 *   extensions → enum types → functions → sequences → tables (columns, PK/UNIQUE/CHECK/EXCLUDE) → sequence ownership
 *   → indexes → foreign keys → views → triggers
 *
 * Everything is schema-qualified (dumped with search_path = pg_catalog) and sorted by name, with no timestamps or
 * sequence positions, so two databases with the same schema produce byte-identical text. Used for
 * `0001_baseline.sql` and for the committed snapshot `db/schema.sql` (db:snapshot / db:snapshot:check).
 *
 * Unsupported objects (domains, composite types, materialized views, partitioned tables, rules, policies) make the
 * dump throw, so the snapshot never silently drops something.
 */
import type { PgClientLike, PgPoolLike } from "./runner";

export type DumpOptions = { excludeTables?: string[]; header?: string };

const q = async (c: PgClientLike, sql: string, params: unknown[] = []) => (await c.query(sql, params)).rows as any[];

export async function dumpSchema(pool: PgPoolLike, opts: DumpOptions = {}): Promise<string> {
  const c = await pool.connect();
  try {
    await c.query("BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY");
    await c.query("SET LOCAL search_path = pg_catalog");
    const out = await dumpWith(c, new Set(opts.excludeTables ?? []));
    await c.query("COMMIT");
    const header = opts.header ?? "-- Schema of the public schema. Generated by src/db/schemaDump.ts — do not edit by hand.";
    return `${header}\n\n${out}`;
  } catch (err) {
    await c.query("ROLLBACK").catch(() => undefined);
    throw err;
  } finally {
    c.release();
  }
}

async function dumpWith(c: PgClientLike, exclude: Set<string>): Promise<string> {
  const ns = `(SELECT oid FROM pg_namespace WHERE nspname = 'public')`;
  const sections: string[] = [];

  // ── unsupported objects ──
  const unsupported = await q(c, `
    SELECT 'domain/composite type ' || t.typname AS what FROM pg_type t
      WHERE t.typnamespace = ${ns} AND (t.typtype = 'd' OR (t.typtype = 'c' AND NOT EXISTS (SELECT 1 FROM pg_class r WHERE r.oid = t.typrelid AND r.relkind <> 'c')))
    UNION ALL SELECT 'materialized view / partitioned or foreign table ' || relname FROM pg_class WHERE relnamespace = ${ns} AND relkind IN ('m', 'p', 'f')
    UNION ALL SELECT 'rule ' || rulename FROM pg_rules WHERE schemaname = 'public'
    UNION ALL SELECT 'policy ' || policyname FROM pg_policies WHERE schemaname = 'public'`);
  if (unsupported.length) throw new Error(`schemaDump: unsupported objects in public: ${unsupported.map((r) => r.what).join(", ")}`);

  // ── extensions ──
  const exts = await q(c, `SELECT extname FROM pg_extension WHERE extname <> 'plpgsql' ORDER BY extname`);
  if (exts.length) sections.push(exts.map((e) => `CREATE EXTENSION IF NOT EXISTS ${ident(e.extname)};`).join("\n"));

  // ── enum types ──
  const enums = await q(c, `
    SELECT t.typname, array_agg(quote_literal(e.enumlabel) ORDER BY e.enumsortorder) AS labels
      FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
     WHERE t.typnamespace = ${ns} GROUP BY t.typname ORDER BY t.typname`);
  if (enums.length) sections.push(enums.map((e) => `CREATE TYPE public.${ident(e.typname)} AS ENUM (${pgArray(e.labels).join(", ")});`).join("\n"));

  // ── functions (not owned by an extension) ──
  const fns = await q(c, `
    SELECT p.proname, pg_get_function_identity_arguments(p.oid) AS args, pg_get_functiondef(p.oid) AS def
      FROM pg_proc p
     WHERE p.pronamespace = ${ns} AND p.prokind IN ('f', 'p')
       AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = p.oid AND d.deptype = 'e')
     ORDER BY p.proname, args`);
  if (fns.length) sections.push(fns.map((f) => `${String(f.def).trim()};`).join("\n\n"));

  // ── sequences (identity sequences are implied by their column) ──
  const seqs = await q(c, `
    SELECT s.sequencename, s.data_type::text AS data_type, s.start_value, s.min_value, s.max_value, s.increment_by, s.cycle, s.cache_size
      FROM pg_sequences s
      JOIN pg_class sc ON sc.relname = s.sequencename AND sc.relnamespace = ${ns}
     WHERE s.schemaname = 'public'
       AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = sc.oid AND d.deptype = 'i')
     ORDER BY s.sequencename`);
  if (seqs.length) {
    sections.push(seqs.map((s) => `CREATE SEQUENCE public.${ident(s.sequencename)} AS ${s.data_type} START WITH ${s.start_value} INCREMENT BY ${s.increment_by} MINVALUE ${s.min_value} MAXVALUE ${s.max_value} CACHE ${s.cache_size}${s.cycle ? " CYCLE" : ""};`).join("\n"));
  }

  // ── tables ──
  const tables = (await q(c, `SELECT oid, relname FROM pg_class WHERE relnamespace = ${ns} AND relkind = 'r' ORDER BY relname`)).filter((t) => !exclude.has(t.relname));
  const tableOids = tables.map((t) => Number(t.oid));
  const cols = await q(c, `
    SELECT a.attrelid AS rel, a.attname, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull, a.attidentity, a.attgenerated,
           pg_get_expr(d.adbin, d.adrelid) AS def,
           CASE WHEN a.attcollation <> 0 AND a.attcollation <> t.typcollation THEN (SELECT quote_ident(collname) FROM pg_collation WHERE oid = a.attcollation) END AS coll
      FROM pg_attribute a
      JOIN pg_type t ON t.oid = a.atttypid
      LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
     WHERE a.attrelid = ANY($1::oid[]) AND a.attnum > 0 AND NOT a.attisdropped
     ORDER BY a.attrelid, a.attnum`, [tableOids]);
  const cons = await q(c, `
    SELECT conrelid AS rel, conname, contype, pg_get_constraintdef(oid, true) AS def
      FROM pg_constraint WHERE conrelid = ANY($1::oid[]) ORDER BY conrelid, contype, conname`, [tableOids]);
  const colsBy = groupBy(cols, (r) => Number(r.rel));
  const consBy = groupBy(cons, (r) => Number(r.rel));
  const order: Record<string, number> = { p: 0, u: 1, c: 2, x: 3 };
  const tableSql: string[] = [];
  for (const t of tables) {
    const lines: string[] = [];
    for (const col of colsBy.get(Number(t.oid)) ?? []) {
      let line = `  ${ident(col.attname)} ${col.type}`;
      if (col.coll) line += ` COLLATE ${col.coll}`;
      if (col.attidentity === "a") line += " GENERATED ALWAYS AS IDENTITY";
      else if (col.attidentity === "d") line += " GENERATED BY DEFAULT AS IDENTITY";
      else if (col.attgenerated === "s") line += ` GENERATED ALWAYS AS (${col.def}) STORED`;
      else if (col.def != null) line += ` DEFAULT ${col.def}`;
      if (col.attnotnull) line += " NOT NULL";
      lines.push(line);
    }
    const inline = (consBy.get(Number(t.oid)) ?? []).filter((k) => k.contype in order).sort((a, b) => order[a.contype] - order[b.contype] || String(a.conname).localeCompare(String(b.conname)));
    for (const k of inline) lines.push(`  CONSTRAINT ${ident(k.conname)} ${k.def}`);
    tableSql.push(`CREATE TABLE public.${ident(t.relname)} (\n${lines.join(",\n")}\n);`);
  }
  if (tableSql.length) sections.push(tableSql.join("\n\n"));

  // ── sequence ownership (SERIAL) ──
  const owned = await q(c, `
    SELECT s.relname AS seq, t.relname AS tbl, a.attname AS col
      FROM pg_depend d
      JOIN pg_class s ON s.oid = d.objid AND s.relkind = 'S'
      JOIN pg_class t ON t.oid = d.refobjid
      JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
     WHERE d.deptype = 'a' AND s.relnamespace = ${ns} ORDER BY s.relname`);
  const ownedSql = owned.filter((o) => !exclude.has(o.tbl)).map((o) => `ALTER SEQUENCE public.${ident(o.seq)} OWNED BY public.${ident(o.tbl)}.${ident(o.col)};`);
  if (ownedSql.length) sections.push(ownedSql.join("\n"));

  // ── indexes that do not back a constraint ──
  const idx = await q(c, `
    SELECT t.relname AS tbl, i.relname AS name, pg_get_indexdef(i.oid) AS def
      FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_class t ON t.oid = x.indrelid
     WHERE t.relnamespace = ${ns} AND t.relkind = 'r'
       AND NOT EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conindid = i.oid AND k.contype IN ('p', 'u', 'x'))
     ORDER BY t.relname, i.relname`);
  const idxSql = idx.filter((r) => !exclude.has(r.tbl)).map((r) => `${r.def};`);
  if (idxSql.length) sections.push(idxSql.join("\n"));

  // ── foreign keys ──
  const fks: string[] = [];
  for (const t of tables) {
    for (const k of (consBy.get(Number(t.oid)) ?? []).filter((k) => k.contype === "f")) {
      fks.push(`ALTER TABLE public.${ident(t.relname)} ADD CONSTRAINT ${ident(k.conname)} ${k.def};`);
    }
  }
  if (fks.length) sections.push(fks.join("\n"));

  // ── views ──
  const views = await q(c, `SELECT relname, pg_get_viewdef(oid, true) AS def FROM pg_class WHERE relnamespace = ${ns} AND relkind = 'v' ORDER BY relname`);
  if (views.length) sections.push(views.map((v) => `CREATE VIEW public.${ident(v.relname)} AS\n${String(v.def).trim().replace(/;$/, "")};`).join("\n\n"));

  // ── triggers ──
  const trg = await q(c, `
    SELECT t.relname AS tbl, g.tgname, pg_get_triggerdef(g.oid, true) AS def
      FROM pg_trigger g JOIN pg_class t ON t.oid = g.tgrelid
     WHERE t.relnamespace = ${ns} AND NOT g.tgisinternal ORDER BY t.relname, g.tgname`);
  const trgSql = trg.filter((r) => !exclude.has(r.tbl)).map((r) => `${r.def};`);
  if (trgSql.length) sections.push(trgSql.join("\n"));

  return sections.join("\n\n") + "\n";
}

function ident(name: string): string {
  return /^[a-z_][a-z0-9_]*$/.test(name) && !RESERVED.has(name) ? name : `"${name.replace(/"/g, '""')}"`;
}

/** Words that must be quoted as identifiers (the subset that occurs or may occur as column names). */
const RESERVED = new Set([
  "all", "analyse", "analyze", "and", "any", "array", "as", "asc", "asymmetric", "both", "case", "cast", "check", "collate", "column",
  "constraint", "create", "current_catalog", "current_date", "current_role", "current_time", "current_timestamp", "current_user",
  "default", "deferrable", "desc", "distinct", "do", "else", "end", "except", "false", "fetch", "for", "foreign", "from", "grant",
  "group", "having", "in", "initially", "intersect", "into", "lateral", "leading", "limit", "localtime", "localtimestamp", "not",
  "null", "offset", "on", "only", "or", "order", "placing", "primary", "references", "returning", "select", "session_user", "some",
  "symmetric", "system_user", "table", "then", "to", "trailing", "true", "union", "unique", "user", "using", "variadic", "when",
  "where", "window", "with", "authorization", "binary", "collation", "concurrently", "cross", "current_schema", "freeze", "full",
  "ilike", "inner", "is", "isnull", "join", "left", "like", "natural", "notnull", "outer", "overlaps", "right", "similar", "tablesample",
  "verbose", "float", "interval", "time", "timestamp", "position", "value", "values", "type", "key", "level", "name", "text", "date",
]);

function pgArray(v: unknown): string[] {
  if (Array.isArray(v)) return v.map(String);
  const s = String(v ?? "").replace(/^\{|\}$/g, "");
  return s ? s.split(",") : [];
}

function groupBy<T>(rows: T[], key: (r: T) => number): Map<number, T[]> {
  const m = new Map<number, T[]>();
  for (const r of rows) {
    const k = key(r);
    const list = m.get(k);
    if (list) list.push(r);
    else m.set(k, [r]);
  }
  return m;
}
